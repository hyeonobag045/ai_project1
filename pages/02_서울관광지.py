    # 지도 생성 (서울 중심)
    m = folium.Map(location=[37.555, 126.985], zoom_start=11.5)
    
    # 마커 추가
    for name, info in seoul_data.items():
        folium.Marker(
            location=[info["lat"], info["lon"]],
            popup=name,
            tooltip=name,
            icon=folium.Icon(color='blue', icon='star', prefix='fa') # 선명한 파란색 별 마커
        ).add_to(m)
    
    # 지도 출력 (width를 100%로 하면 컬럼의 60% 비중을 꽉 채움)
    st_folium(m, width="100%", height=500, returned_objects=[])

